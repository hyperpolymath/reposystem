#!/bin/bash
# Commit script for Pinned-Dependencies fixes
# Commits all workflow changes with standardized message

set -euo pipefail

git config --global user.name "Mistral Vibe"
git config --global user.email "vibe@mistral.ai"

COMMITTED=0
SKIPPED=0
TOTAL=0

for repo_path in $(find /home/hyperpolymath/developer/hyper-repos /home/hyperpolymath/developer/meta-repos -type d -name ".git" -printf "%h\n" 2>/dev/null); do
    TOTAL=$((TOTAL + 1))
    
    if [ ! -d "$repo_path/.git" ]; then
        continue
    fi
    
    cd "$repo_path"
    
    # Check for workflow changes
    if [ -d ".github/workflows" ] && ! git diff --quiet .github/workflows/ 2>/dev/null; then
        repo_name=$(basename "$repo_path")
        echo "[$TOTAL] Committing $repo_name..."
        
        git add .github/workflows/
        git commit -m "Fix Pinned-Dependencies: pin GitHub Actions to immutable SHAs

Pin all uses: references to full 40-char commit SHAs to prevent
supply-chain attacks via mutable tags or branches. This resolves
Scorecard Pinned-Dependencies alerts and Hypatia WH004 findings.

Generated by Mistral Vibe.
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>" 2>&1 | tail -1
        COMMITTED=$((COMMITTED + 1))
    else
        SKIPPED=$((SKIPPED + 1))
    fi
    
    cd /home/hyperpolymath/developer
done

echo ""
echo "=========================================="
echo "Pinned-Dependencies Fix Commit Summary"
echo "=========================================="
echo "Total repos checked: $TOTAL"
echo "Commits created: $COMMITTED"
echo "Skipped (no changes): $SKIPPED"
echo ""
echo "Next: Push commits to GitHub"
echo "  bash scripts/push_all_token_fix_commits.sh"

# Create and merge PRs for CI/CD fixes

set -euo pipefail

BRANCH_NAME="chore/apply-foundation-ci-fixes-20260911"
PR_TITLE="fix(ci): apply foundation CI/CD security fixes"
PR_BODY="Apply foundational CI/CD security fixes

- Update CodeQL workflow to SHA-pinned actions with persist-credentials: false
- Update reusable workflow pins to current standards main SHAs
- Add persist-credentials: false to all checkout actions

Generated by Mistral Vibe
Co-Authored-By: Mistral Vibe <vibe@mistral.ai>"

REPOS=(
    "/home/hyperpolymath/developer/hyper-repos/jtv-halting-islands-ct"
    "/home/hyperpolymath/developer/hyper-repos/metadatastician/idaptik-ums"
    "/home/hyperpolymath/developer/hyper-repos/_EXTENSIONS _SET/oikosbot"
    "/home/hyperpolymath/developer/hyper-repos/_OPM (other peoples repos) _SET/awesome-idris2"
    "/home/hyperpolymath/developer/hyper-repos/_RSR _SET/rsr-julia-library-template-repo"
    "/home/hyperpolymath/developer/hyper-repos/_RSR _SET/rsr-template-repo"
    "/home/hyperpolymath/developer/hyper-repos/_JULIA_LIBRARIES _SET/Cliometrics.jl"
    "/home/hyperpolymath/developer/hyper-repos/_JULIA_LIBRARIES _SET/Cliodynamics.jl"
    "/home/hyperpolymath/developer/hyper-repos/_JULIA_LIBRARIES _SET/JuliaForChildren.jl"
    "/home/hyperpolymath/developer/hyper-repos/_WORK _SET/academic-workflow-suite"
    "/home/hyperpolymath/developer/hyper-repos/proven-tests-and-benches"
    "/home/hyperpolymath/developer/hyper-repos/_HARDWARE _SET/neurophone"
    "/home/hyperpolymath/developer/hyper-repos/_DATABASE _SET/hermeneia"
    "/home/hyperpolymath/developer/hyper-repos/_NETWORK _SET/ipv6-tools"
    "/home/hyperpolymath/developer/hyper-repos/_NETWORK _SET/ipfs-overlay"
    "/home/hyperpolymath/developer/hyper-repos/casket-ssg"
    "/home/hyperpolymath/developer/meta-repos/universal-modding-studio"
)

TOTAL=${#REPOS[@]}
echo "Total repos to process: $TOTAL"
echo ""

SUCCESS=0
FAILED=0
SKIPPED=0
PROCESSED=0

for repo_path in "${REPOS[@]}"; do
    PROCESSED=$((PROCESSED + 1))
    repo_name=$(basename "$repo_path")
    
    if [[ "$repo_path" == *"hyper-repos/"* ]]; then
        org="hyperpolymath"
    elif [[ "$repo_path" == *"meta-repos/"* ]]; then
        org="metadatastician"
    else
        SKIPPED=$((SKIPPED + 1))
        echo "[$PROCESSED] $repo_name: Unknown org, skipping"
        continue
    fi
    
    echo "[$PROCESSED/$TOTAL] Processing: $org/$repo_name"
    cd "$repo_path"
    
    if ! git rev-parse "origin/$BRANCH_NAME" >/dev/null 2>&1; then
        echo "  Branch $BRANCH_NAME not found, skipping"
        SKIPPED=$((SKIPPED + 1))
        continue
    fi
    
    EXISTING_PR=$(gh pr list --head "$BRANCH_NAME" --json number --jq '.[] | .number' 2>/dev/null || true)
    
    if [[ -n "$EXISTING_PR" ]]; then
        echo "  PR #$EXISTING_PR already exists"
        echo "  Attempting to merge..."
        MERGE_OUTPUT=$(gh pr merge "$EXISTING_PR" --squash --auto 2>&1 || true)
        if echo "$MERGE_OUTPUT" | grep -q "Merged"; then
            echo "  SUCCESS: MERGED"
            SUCCESS=$((SUCCESS + 1))
        else
            echo "  WARNING: Merge blocked"
            FAILED=$((FAILED + 1))
        fi
    else
        echo "  Creating new PR..."
        PR_OUTPUT=$(gh pr create --base main --head "$BRANCH_NAME" --title "$PR_TITLE" --body "$PR_BODY" 2>&1 || true)
        if echo "$PR_OUTPUT" | grep -q "Pull request"; then
            PR_NUM=$(echo "$PR_OUTPUT" | grep -oE '/pull/[0-9]+' | sed 's|/pull/||' | head -1)
            if [[ -n "$PR_NUM" ]]; then
                echo "  PR #$PR_NUM created"
                AUTO_OUTPUT=$(gh pr merge "$PR_NUM" --squash --auto 2>&1 || true)
                echo "  Auto-merge: $(echo "$AUTO_OUTPUT" | tail -1)"
                echo "  SUCCESS: PR CREATED"
                SUCCESS=$((SUCCESS + 1))
            else
                echo "  WARNING: Could not get PR number"
                FAILED=$((FAILED + 1))
            fi
        else
            echo "  ERROR: PR creation failed"
            FAILED=$((FAILED + 1))
        fi
    fi
    echo ""
done

echo "=========================================="
echo "Summary: Total=$TOTAL, Success=$SUCCESS, Failed=$FAILED, Skipped=$SKIPPED"
echo "=========================================="
